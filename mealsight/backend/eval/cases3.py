"""Dimension 3's 30 hand-derived match-accuracy cases.

HOW THE EXPECTED VALUES WERE DERIVED (read this before trusting them)
---------------------------------------------------------------------
Every expected outcome below was worked out BY HAND, before the matcher was run
on any of these cases, from three inputs only:

  1. The recipe's real ingredient rows (name + importance), read from the seeded
     recipes table.
  2. The reference data the matcher is documented to read: the ingredient_synonyms
     table (147 rows) and the substitutions table (57 rows), dumped and read in full.
  3. The matcher's DOCUMENTED rules (the docstrings in mealsight/matching/): a name is
     normalized (lowercase, punctuation out, plurals singularized, container words
     and prep modifiers such as "fresh"/"chopped"/"plain" stripped, protected
     multi-word terms kept whole), then resolved through the synonym table; a pantry
     item that is a MORE specific cut/colour of the requirement ("chicken thighs" for
     "chicken") is a full match, a LESS specific one is a partial; otherwise a
     substitution is tried, then the ingredient is missing; the score is
     (matched + 0.7 * (substituted + partial)) / total entries, minus 0.3 per missing
     CRITICAL ingredient, clamped to [0, 1]; can_cook needs score >= 0.5 and no
     critical ingredient missing.

Each case's `derivation` states the working. `basis` says what the expectation rests on:
  "rule"    -> follows from the documented rules above.
  "intent"  -> follows from what the ingredient means; the documented rules do not
               cover it. Where the matcher disagrees on an "intent" case it is reported
               as a disagreement with the judgement spelled out, not silently counted.

The numbers were NOT generated by running the matcher, which would make the test a
tautology. Long-expired exclusion and avoid-list exclusion are not part of
match_recipe itself; the harness applies the same production functions the pipeline
uses (usable_pantry_names, mealsight.matching.avoid) and the expectations say what
should happen.
"""

